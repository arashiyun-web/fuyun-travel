// Provisions the isolated cloud environment for the PR #33 Preview E2E. Run on 8940 after the
// official CLI logins (neonctl auth, wrangler login). Every secret goes straight into the
// ACL-protected %USERPROFILE%\.fuyun-secrets\preview-e2e.env (or into Vercel via stdin) and is never
// printed or passed on a command line.
//
//   node scripts/test-support/provision-preview-e2e.mjs neon       # schema-only branch + own role
//   node scripts/test-support/provision-preview-e2e.mjs migrate    # history rows + migrate deploy on that branch
//   node scripts/test-support/provision-preview-e2e.mjs secrets    # test admin login, cron/access tokens, IG key
//   node scripts/test-support/provision-preview-e2e.mjs r2-bucket  # private test bucket (wrangler)
//   node scripts/test-support/provision-preview-e2e.mjs vercel-env # branch-scoped Preview env for the PR branch
//   node scripts/test-support/provision-preview-e2e.mjs status     # names and fingerprints only
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync, spawnSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import path from "node:path";

const HOME = process.env.USERPROFILE;
const SECRETS = path.join(HOME, ".fuyun-secrets");
const ENV_FILE = path.join(SECRETS, "preview-e2e.env");
const ADMIN_DIR = path.join(SECRETS, "preview-e2e-admin");
const HISTORY_SQL = path.join(HOME, ".fuyun-tools", "migration-rehearsal", "prisma-migrations-history.sql");
const PSQL = path.join(HOME, ".fuyun-tools", "pgsql-17", "pgsql", "bin", "psql.exe");
const NEONCTL = ["-y", "neonctl@6.2.3"];
const WRANGLER = ["-y", "wrangler@4.142.0"];
const BRANCH_NAME = "pr33-ops-e2e";
const ROLE_NAME = "e2e_app";
const BUCKET = "fuyun-ops-pr33-e2e";
const GIT_BRANCH = "feat/ops-worker-integration-20260927";
const VERCEL_SCOPE = ["--scope", "arashiyun-s-projects", "--project", "fuyun-travel"];
// Every database variable the Vercel Neon integration shares with Production/Preview/Development.
// All of them get a branch-scoped Preview override so nothing in this branch's Preview resolves to production.
const DB_VARS = ["DATABASE_URL", "DATABASE_URL_UNPOOLED", "POSTGRES_URL", "POSTGRES_PRISMA_URL", "POSTGRES_URL_NON_POOLING", "POSTGRES_URL_NO_SSL", "POSTGRES_HOST", "POSTGRES_USER", "POSTGRES_PASSWORD", "POSTGRES_DATABASE", "PGHOST", "PGHOST_UNPOOLED", "PGUSER", "PGPASSWORD", "PGDATABASE", "NEON_PROJECT_ID"];

const readEnv = (file) => (existsSync(file) ? Object.fromEntries(readFileSync(file, "utf8").split(/\r?\n/).filter((l) => /^[A-Z0-9_]+=/.test(l)).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim()])) : {});
const fp = (v) => (v ? createHash("sha256").update(v).digest("hex").slice(0, 10) : "-");
const endpointOf = (url) => new URL(url).hostname.split(".")[0].replace(/-pooler$/, "");

function saveEnv(updates) {
  const merged = { ...readEnv(ENV_FILE), ...updates };
  const body = "# PR #33 Preview E2E (isolated test resources only). Not in Git. Generated by provision-preview-e2e.mjs\n" + Object.entries(merged).map(([k, v]) => `${k}=${v}`).join("\n") + "\n";
  writeFileSync(ENV_FILE, body, { encoding: "utf8" }); // inherits the .fuyun-secrets ACL (current user + SYSTEM)
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: "utf8", shell: process.platform === "win32" && /^(npx|vercel)$/.test(cmd), ...opts });
  if (r.status !== 0) throw new Error(`${cmd} ${args.filter((a) => !a.startsWith("postgres")).slice(0, 4).join(" ")} failed: ${(r.stderr || "").replace(/postgres(ql)?:\/\/\S+/g, "<url>").slice(0, 300)}`);
  return r.stdout;
}
const neon = (args) => JSON.parse(run("npx", [...NEONCTL, ...args, "--output", "json"]));

async function stepNeon() {
  const prod = readEnv(path.join(SECRETS, "neon-prod.env")).DATABASE_URL;
  const prodEndpoint = endpointOf(prod);
  const asList = (x, key) => (Array.isArray(x) ? x : x[key] || []);
  // Vercel-managed Neon accounts live in an org; neonctl prompts for it unless --org-id is given.
  const projects = neon(["projects", "list", ...(process.env.NEON_ORG_ID ? ["--org-id", process.env.NEON_ORG_ID] : [])]);
  const list = [...asList(projects, "projects"), ...(projects.shared_with_me || [])];
  // Identify the production project and branch by the endpoint host of the production DATABASE_URL.
  // The connection string output stays in memory; only the endpoint id is compared.
  let project;
  let parent;
  for (const p of list) {
    for (const b of asList(neon(["branches", "list", "--project-id", p.id]), "branches")) {
      // Explicit role/database avoid neonctl's interactive picker when a branch has several.
      const cs = spawnSync("npx", [...NEONCTL, "connection-string", b.id, "--project-id", p.id, "--role-name", decodeURIComponent(new URL(prod).username), "--database-name", new URL(prod).pathname.slice(1)], { encoding: "utf8", shell: true });
      if (cs.status === 0 && cs.stdout.includes(prodEndpoint)) {
        project = p;
        parent = b;
        break;
      }
    }
    if (project) break;
  }
  if (!project || !parent) throw new Error("could not identify the production project/branch from the production endpoint");
  const existing = asList(neon(["branches", "list", "--project-id", project.id]), "branches").find((b) => b.name === BRANCH_NAME);
  if (!existing) run("npx", [...NEONCTL, "branches", "create", "--project-id", project.id, "--name", BRANCH_NAME, "--parent", parent.id, "--schema-only", "--no-secrets", "--output", "json"]);
  const roles = neon(["roles", "list", "--project-id", project.id, "--branch", BRANCH_NAME]);
  if (!asList(roles, "roles").some((r) => r.name === ROLE_NAME)) {
    run("npx", [...NEONCTL, "roles", "create", "--project-id", project.id, "--branch", BRANCH_NAME, "--name", ROLE_NAME, "--output", "json"]);
  }
  const database = new URL(prod).pathname.slice(1);
  const conn = (pooled) => run("npx", [...NEONCTL, "connection-string", BRANCH_NAME, "--project-id", project.id, "--role-name", ROLE_NAME, "--database-name", database, ...(pooled ? ["--pooled"] : []), "--ssl", "require"]).trim();
  const pooled = conn(true);
  const direct = conn(false);
  if (endpointOf(pooled) === prodEndpoint) throw new Error("new branch resolved to the production endpoint — aborting");
  saveEnv({ PREVIEW_NEON_PROJECT_ID: project.id, PREVIEW_NEON_BRANCH: BRANCH_NAME, PREVIEW_DATABASE_URL: pooled, PREVIEW_DATABASE_URL_UNPOOLED: direct });
  console.log(`neon: project=${project.id} parent=${parent.name} branch=${BRANCH_NAME} role=${ROLE_NAME} endpoint=${endpointOf(pooled)} (production endpoint ${prodEndpoint}: different)`);
}

function stepMigrate() {
  const env = readEnv(ENV_FILE);
  const url = env.PREVIEW_DATABASE_URL_UNPOOLED;
  if (!url) throw new Error("run the neon step first");
  const u = new URL(url);
  const pg = { ...process.env, PGHOST: u.hostname, PGUSER: decodeURIComponent(u.username), PGPASSWORD: decodeURIComponent(u.password), PGDATABASE: u.pathname.slice(1), PGSSLMODE: "require" };
  const count = (sql) => Number(run(PSQL, ["-Atc", sql], { env: pg }).trim());
  const tables = count("select count(*) from information_schema.tables where table_schema='public'");
  const rows = count("select (select count(*) from charter_quotes)+(select count(*) from inquiries)+(select count(*) from line_sessions)+(select count(*) from articles)");
  if (rows !== 0) throw new Error("branch holds data rows — not a schema-only branch; aborting");
  if (count("select count(*) from _prisma_migrations") === 0) run(PSQL, ["-q", "-v", "ON_ERROR_STOP=1", "-f", HISTORY_SQL], { env: pg });
  // DDL runs as the branch's owner role, as it will in production; the runtime role e2e_app has no CREATE
  // on schema public (first attempt: 42501). The owner URL is resolved on the test branch and kept in memory.
  const prod = new URL(readEnv(path.join(SECRETS, "neon-prod.env")).DATABASE_URL);
  const owner = run("npx", [...NEONCTL, "connection-string", env.PREVIEW_NEON_BRANCH, "--project-id", env.PREVIEW_NEON_PROJECT_ID, "--role-name", decodeURIComponent(prod.username), "--database-name", prod.pathname.slice(1)]).trim();
  if (endpointOf(owner) !== endpointOf(url) || endpointOf(owner) === endpointOf(prod.toString())) throw new Error("owner URL is not on the test branch endpoint");
  const out = run("npx", ["prisma", "migrate", "deploy"], { env: { ...process.env, DATABASE_URL: owner } });
  const applied = count("select count(*) from _prisma_migrations where finished_at is not null");
  console.log(`migrate: public tables before=${tables}, data rows=${rows}, history rows=${applied}; ${/202609280001/.test(out) ? "applied 202609280001_add_operations_tables" : "nothing new applied"}`);
}

function stepSecrets() {
  execFileSync(process.execPath, ["scripts/provision-admin-credentials.mjs", "--username", "preview-e2e-admin", "--out", ADMIN_DIR], { stdio: "ignore" });
  const auth = readEnv(path.join(ADMIN_DIR, "admin-auth.env"));
  const password = readFileSync(path.join(ADMIN_DIR, "admin-login.txt"), "utf8").match(/密碼: (.+)/)[1].trim();
  const tok = () => randomBytes(32).toString("base64url");
  saveEnv({
    PREVIEW_ADMIN_USERNAME: auth.ADMIN_USERNAME,
    PREVIEW_ADMIN_PASSWORD: password,
    PREVIEW_ADMIN_PASSWORD_SALT: auth.ADMIN_PASSWORD_SALT,
    PREVIEW_ADMIN_PASSWORD_HASH: auth.ADMIN_PASSWORD_HASH,
    PREVIEW_JWT_SECRET: auth.JWT_SECRET,
    PREVIEW_OPERATIONS_CRON_TOKEN: tok(),
    PREVIEW_ADMIN_ACCESS_TOKEN: tok(),
    PREVIEW_INSTAGRAM_LOGIN_TOKEN_ENCRYPTION_KEY: randomBytes(32).toString("base64"),
  });
  console.log("secrets: test admin login, JWT secret, cron token, access token and IG key generated (values not shown)");
}

function stepBucket() {
  const who = run("npx", [...WRANGLER, "whoami"]);
  const account = (who.match(/\b[0-9a-f]{32}\b/) || [])[0];
  const list = run("npx", [...WRANGLER, "r2", "bucket", "list"]);
  if (!list.includes(BUCKET)) run("npx", [...WRANGLER, "r2", "bucket", "create", BUCKET]);
  saveEnv({ R2_ACCOUNT_ID: account, R2_BUCKET_NAME: BUCKET });
  console.log(`r2: account=${account} bucket=${BUCKET} (private; no r2.dev or custom domain attached)`);
}

function addBranchEnv(name, value) {
  spawnSync("vercel", ["env", "rm", name, "preview", GIT_BRANCH, "--yes", ...VERCEL_SCOPE], { shell: true, encoding: "utf8" });
  run("vercel", ["env", "add", name, "preview", GIT_BRANCH, ...VERCEL_SCOPE], { input: value });
}

function stepVercelEnv() {
  const e = readEnv(ENV_FILE);
  const need = ["PREVIEW_DATABASE_URL", "PREVIEW_DATABASE_URL_UNPOOLED", "R2_ACCOUNT_ID", "R2_BUCKET_NAME", "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "PREVIEW_ADMIN_USERNAME", "PREVIEW_OPERATIONS_CRON_TOKEN"];
  const missing = need.filter((k) => !e[k]);
  if (missing.length) throw new Error(`missing: ${missing.join(", ")}`);
  const pooled = new URL(e.PREVIEW_DATABASE_URL);
  const direct = new URL(e.PREVIEW_DATABASE_URL_UNPOOLED);
  const noSsl = new URL(e.PREVIEW_DATABASE_URL);
  noSsl.search = "";
  const db = {
    DATABASE_URL: e.PREVIEW_DATABASE_URL,
    DATABASE_URL_UNPOOLED: e.PREVIEW_DATABASE_URL_UNPOOLED,
    POSTGRES_URL: e.PREVIEW_DATABASE_URL,
    POSTGRES_PRISMA_URL: e.PREVIEW_DATABASE_URL,
    POSTGRES_URL_NON_POOLING: e.PREVIEW_DATABASE_URL_UNPOOLED,
    POSTGRES_URL_NO_SSL: noSsl.toString(),
    POSTGRES_HOST: pooled.hostname,
    POSTGRES_USER: decodeURIComponent(pooled.username),
    POSTGRES_PASSWORD: decodeURIComponent(pooled.password),
    POSTGRES_DATABASE: pooled.pathname.slice(1),
    PGHOST: pooled.hostname,
    PGHOST_UNPOOLED: direct.hostname,
    PGUSER: decodeURIComponent(pooled.username),
    PGPASSWORD: decodeURIComponent(pooled.password),
    PGDATABASE: pooled.pathname.slice(1),
    NEON_PROJECT_ID: e.PREVIEW_NEON_PROJECT_ID,
  };
  const app = {
    OPERATIONS_PERSISTENCE_MODE: "database",
    OPERATIONS_LIVE_PUBLISH_ENABLED: "false",
    OPERATIONS_CRON_TOKEN: e.PREVIEW_OPERATIONS_CRON_TOKEN,
    ADMIN_ACCESS_TOKEN: e.PREVIEW_ADMIN_ACCESS_TOKEN,
    ADMIN_USERNAME: e.PREVIEW_ADMIN_USERNAME,
    ADMIN_PASSWORD_SALT: e.PREVIEW_ADMIN_PASSWORD_SALT,
    ADMIN_PASSWORD_HASH: e.PREVIEW_ADMIN_PASSWORD_HASH,
    JWT_SECRET: e.PREVIEW_JWT_SECRET,
    INSTAGRAM_LOGIN_TOKEN_ENCRYPTION_KEY: e.PREVIEW_INSTAGRAM_LOGIN_TOKEN_ENCRYPTION_KEY,
    R2_ACCOUNT_ID: e.R2_ACCOUNT_ID,
    R2_ACCESS_KEY_ID: e.R2_ACCESS_KEY_ID,
    R2_SECRET_ACCESS_KEY: e.R2_SECRET_ACCESS_KEY,
    R2_BUCKET_NAME: e.R2_BUCKET_NAME,
  };
  for (const name of DB_VARS) addBranchEnv(name, db[name]);
  for (const [name, value] of Object.entries(app)) addBranchEnv(name, value);
  console.log(`vercel: ${DB_VARS.length + Object.keys(app).length} branch-scoped Preview vars set for ${GIT_BRANCH} (Production untouched)`);
}

function stepStatus() {
  const e = readEnv(ENV_FILE);
  for (const [k, v] of Object.entries(e)) console.log(`${k}: ${/URL$|UNPOOLED$/.test(k) ? `endpoint=${endpointOf(v)} fp=${fp(v)}` : /ID$|NAME$|BRANCH$|USERNAME$/.test(k) ? v : `set fp=${fp(v)}`}`);
}

// When the bucket was created in the dashboard (wrangler's OAuth scope has no R2 access).
function stepR2Record() {
  const who = run("npx", [...WRANGLER, "whoami"]);
  const account = (who.match(/\b[0-9a-f]{32}\b/) || [])[0];
  if (!account) throw new Error("account id not found in wrangler whoami");
  saveEnv({ R2_ACCOUNT_ID: account, R2_BUCKET_NAME: BUCKET });
  console.log(`r2: recorded account=${account} bucket=${BUCKET}`);
}

const steps = { "r2-record": stepR2Record, neon: stepNeon, migrate: stepMigrate, secrets: stepSecrets, "r2-bucket": stepBucket, "vercel-env": stepVercelEnv, status: stepStatus };
const step = steps[process.argv[2]];
if (!step) {
  console.error(`usage: provision-preview-e2e.mjs ${Object.keys(steps).join("|")}`);
  process.exit(2);
}
await step();
